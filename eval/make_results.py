#!/usr/bin/env python3
"""Write RESULTS.md from the outputs of the other scripts. No number in RESULTS.md is typed by hand.

    make results        # re-runs ab_test.py, judge_agreement.py, the regression suite, then this script
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from callqc.labels import load_human_labels  # noqa: E402
from callqc.regression import load_cases, run_suite  # noqa: E402
from callqc.vaani_adapter import Variant  # noqa: E402


def pct(c: dict) -> str:
    return f"{c['mean']:.1%} (95% CI {c['lo']:.1%} – {c['hi']:.1%})"


def fp(p: float) -> str:
    return "< 0.00001" if p < 1e-5 else f"{p:.3g}"


def main() -> None:
    ab = json.loads((ROOT / "results/ab/latest.json").read_text())
    ja = json.loads((ROOT / "results/judge_agreement.json").read_text())
    production = yaml.safe_load((ROOT / "prompts/production.yaml").read_text())["production"]
    cases = load_cases()
    suite = run_suite(Variant.load(ROOT / "prompts" / production), verbose=False)
    n_labels = len(load_human_labels())

    control = ab["control"]
    real = {v: s for v, s in ab["variants"].items() if v != "v0_sanity_bad"}
    best = max((v for v in real if v != control), key=lambda v: real[v]["conversion"]["mean"])
    comp = ab["comparisons"][best]["converted"]
    n_calls = sum(s["n_calls"] for s in ab["variants"].values())

    L = ["# Results", "",
         "Generated by `python eval/make_results.py` from `results/ab/latest.json` (ab_test.py), "
         "`results/judge_agreement.json` (eval/judge_agreement.py) and the regression suite. "
         "Re-run everything with `make results`.", "",
         f"_Config: {ab['config']['calls_per_persona']} calls per persona × {len(ab['config']['personas'])} personas, "
         f"seed {ab['config']['seed']}, judges `{ab['config']['judges']}`, rubric v{ab['config']['rubric_version']}, "
         f"generated {ab['generated_at']}._", "",
         "## Headline numbers", "",
         "| Metric | Value |", "|---|---|",
         f"| Hand-labelled calls | {n_labels} |",
         f"| Prompt variants tested | {len(real)} (+1 sanity-check bad prompt) |",
         f"| Simulated calls | {n_calls} |",
         f"| Baseline conversion ({control}) | {pct(ab['variants'][control]['conversion'])} |",
         f"| Best variant conversion ({best}) | {pct(ab['variants'][best]['conversion'])} |",
         f"| Lift, best vs baseline | {comp['diff']:+.1%} (95% CI {comp['lo']:+.1%} – {comp['hi']:+.1%}), "
         f"Fisher p = {fp(comp['p'])}, Holm p = {fp(comp['p_holm'])} |",
         f"| Regression tests | {len(cases)} ({suite['n_cases'] - len(suite['failed']) - len(suite['known_issues_failing'])} "
         f"passing on production `{production}`, {len(suite['known_issues_failing'])} tracked known issue) |",
         ""]

    L += ["## Judge agreement", ""]
    for r in ja["results"]:
        ref = "human labels" if r["mode"] == "human" else "the other two judges (inter-judge; no human labels yet)"
        L += [f"**{r['rubric']}** — {r['n_calls']} calls, reference = {ref}", "",
              "| Judge | Agreement | Cohen's κ |", "|---|---|---|"]
        for name, j in r["judges"].items():
            L.append(f"| {name} | {j['overall']['pct']:.1f}% | {j['overall']['kappa']:.3f} |")
        L.append("")
    if ja["n_human_labelled"] == 0:
        L += ["Human-vs-judge agreement (single judge vs panel) is computed by the same script once labels exist: "
              "label calls with `streamlit run apps/label_app.py`, then `make results`.", ""]

    L += ["## A/B results", "",
          "| Variant | Conversion | Applied or callback | Rubric /16 | QC fail rate | Turns |", "|---|---|---|---|---|---|"]
    for v, s in ab["variants"].items():
        L.append(f"| {v} | {pct(s['conversion'])} | {s['positive_outcome']['mean']:.1%} | "
                 f"{s['rubric_total']['mean']:.2f} [{s['rubric_total']['lo']:.2f}, {s['rubric_total']['hi']:.2f}] | "
                 f"{s['qc_fail_rate']['mean']:.1%} | {s['call_turns']['mean']:.1f} |")
    L += ["", f"Comparisons vs `{control}` (Fisher exact on conversion, permutation test on rubric total, "
          "Holm-corrected across variants):", "",
          "| Variant | Δ conversion [95% CI] | Holm p | Δ rubric [95% CI] | Holm p |", "|---|---|---|---|---|"]
    for v, c in ab["comparisons"].items():
        cv, t = c["converted"], c["total"]
        L.append(f"| {v} | {cv['diff']:+.1%} [{cv['lo']:+.1%}, {cv['hi']:+.1%}] | {fp(cv['p_holm'])}"
                 f"{' ✓' if cv['significant'] else ''} | {t['diff']:+.2f} [{t['lo']:+.2f}, {t['hi']:+.2f}] | "
                 f"{t['p_holm']:.3g}{' ✓' if t['significant'] else ''} |")
    L += ["", "Per-criterion means:", "", "| Variant | " + " | ".join(ab["variants"][control]["criteria"]) + " |",
          "|---" * (1 + len(ab["variants"][control]["criteria"])) + "|"]
    for v, s in ab["variants"].items():
        L.append(f"| {v} | " + " | ".join(f"{x:.2f}" for x in s["criteria"].values()) + " |")
    L += ["", "## Caveats", "",
          "- Callers are simulated. Persona hidden conditions were written together with the variant hypotheses, "
          "so these lifts show the harness detects the effects it was built to test. They are not evidence of "
          "real-world conversion; that needs a live holdout.",
          "- Offline runs use rule-based judges and Vaani's MockLLM with each variant's policy switches. "
          "`--judges claude` and a real Vaani LLM backend run the same pipeline end to end.", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(L))
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
